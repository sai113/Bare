# Refreshes the filter lists in data/:
#   easylist.txt     ads                       (EasyList, GPLv3 / CC BY-SA 3.0, https://easylist.to)
#   easyprivacy.txt  trackers                  (EasyPrivacy, GPLv3 / CC BY-SA 3.0, https://easylist.to)
#   hagezi-pro.txt   ads, trackers, device/app telemetry (HaGeZi Multi PRO, GPLv3, https://github.com/hagezi/dns-blocklists)
#   fanboy-social.txt    optional: social widgets (Fanboy's Social Blocking List, GPLv3 / CC BY-SA 3.0)
#   easylist-cookie.txt  optional: cookie banners (EasyList Cookie List, CC BY 3.0)
# bare-extra.txt is Bare's own list and is edited by hand, not downloaded.
#   blocklist.txt    ad/tracking/malware hosts (StevenBlack unified hosts, MIT, https://github.com/StevenBlack/hosts)
# Usage: pwsh scripts/update-blocklist.ps1

$ErrorActionPreference = "Stop"
$data = Join-Path $PSScriptRoot "..\data"
New-Item -ItemType Directory -Force $data | Out-Null
$data = (Resolve-Path $data).Path

foreach ($list in @(
    @{ Name = "easylist.txt";    Url = "https://easylist.to/easylist/easylist.txt" },
    @{ Name = "easyprivacy.txt"; Url = "https://easylist.to/easylist/easyprivacy.txt" },
    @{ Name = "hagezi-pro.txt";  Url = "https://raw.githubusercontent.com/hagezi/dns-blocklists/main/adblock/pro.txt" },
    @{ Name = "fanboy-social.txt";   Url = "https://easylist.to/easylist/fanboy-social.txt" },
    @{ Name = "easylist-cookie.txt"; Url = "https://secure.fanboy.co.nz/fanboy-cookiemonster.txt" }
)) {
    $text = (Invoke-WebRequest -Uri $list.Url -UseBasicParsing).Content
    if ($text -notmatch '^\[Adblock Plus') { throw "$($list.Url) did not return a filter list" }
    [IO.File]::WriteAllText("$data\$($list.Name)", $text)
    "Wrote $($list.Name) ($((($text -split "`n").Count)) lines)"
}

$source = "https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"
$hosts = (Invoke-WebRequest -Uri $source -UseBasicParsing).Content -split "`n"
$domains = foreach ($line in $hosts) {
    if ($line -match '^0\.0\.0\.0\s+([a-z0-9][a-z0-9.-]*\.[a-z0-9-]+)\s*(#.*)?$') {
        $d = $Matches[1].ToLowerInvariant()
        if ($d -ne "0.0.0.0") { $d }
    }
}
$domains = $domains | Sort-Object -Unique
$header = @(
    "# Bare blocklist: one domain per line, subdomains are blocked too."
    "# Generated by scripts/update-blocklist.ps1 on $(Get-Date -Format yyyy-MM-dd)"
    "# Source: $source (MIT License, Copyright (c) Steven Black)"
)
[IO.File]::WriteAllLines("$data\blocklist.txt", [string[]]($header + $domains))
"Wrote blocklist.txt ($($domains.Count) domains)"
